/**
 * 把大漠 GetLastError 返回码转成友好消息
 * @param code 大漠错误码(正整数表示无错误,负数表示错误)
 */
export function dmErrorMessage(code: number): string {
  if (code === 0) return MESSAGES[0];
  return MESSAGES[code] || `未知错误(错误码 ${code})`;
}

/**
 * 给"该怎么修"的建议(空字符串表示无特定建议)
 */
export function dmErrorAdvice(code: number): string {
  if (code === 0) return '';
  return ADVICE[code] || '';
}

/**
 * 一次性返回"消息 + 建议",用于 worker 内部日志和 dialog/UI 显示
 */
export function dmErrorFull(code: number): { message: string; advice: string } {
  return { message: dmErrorMessage(code), advice: dmErrorAdvice(code) };
}